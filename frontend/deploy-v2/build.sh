#!/bin/bash
# build.sh — the read-only live preview of the refined 团队线路管理 UI, as a static tree for /admin/v2/.
#
#   deploy/v2/build.sh            → deploy/v2/dist/   (rm -rf first; same input → same bytes, same build id)
#   WRITES=1 deploy/v2/build.sh   → same, with the team-ops DB write actions enabled (default: read-only preview)
#
# Layout (relative URLs are the prototype's own, so nothing in the page code changes):
#   dist/app/        prototype/original-refined  (index.html, css/, js/, assets/ only — no shots, critique,
#                    tools, compare*, README, final/)
#   dist/shared/     prototype/shared without tests / smoke page / README; index.js is GENERATED: it re-exports
#                    the prototype barrel (renamed index.proto.js) with loadSnapshot → live adapter and
#                    createLive → live poller (deploy/v2/live/boot.js)
#   dist/original/   tokens.css + fonts/            (app/css/app.css imports ../../original/tokens.css)
#   dist/data/       plan-catalog.json only         (app/js/plans.js fetches ../../data/plan-catalog.json)
#   dist/live/       adapter.js, synth.js, boot.js  (never fixtures)
#
# app/index.html is rewritten for the production CSP (script-src 'self'): its inline theme script becomes
# js/theme-init.js, js/live-flag.js sets globalThis.TEAMOPS_LIVE before the module script, the snapshot
# preload is removed, and <meta name="teamops-build"> carries the content hash.  Then tools/dist.mjs check
# verifies every URL, the data-file and real-IP rules, and CSP hazards, and prints the size summary.
set -euo pipefail
export COPYFILE_DISABLE=1 LC_ALL=C
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
P="$ROOT/prototype"
DIST="$HERE/dist"
NODE=${NODE:-$HOME/.local/bin/node}
[ -x "$NODE" ] || NODE=$HOME/.local/opt/node/bin/node

for f in "$P/original-refined/index.html" "$P/original-refined/js/app.js" "$P/shared/index.js" "$P/original/tokens.css" "$P/data/plan-catalog.json" "$HERE/live/adapter.js" "$HERE/live/synth.js" "$HERE/live/boot.js"; do
  [ -f "$f" ] || { echo "missing input: $f" >&2; exit 1; }
done

rm -rf "$DIST"
mkdir -p "$DIST/app" "$DIST/shared" "$DIST/original" "$DIST/data" "$DIST/live"

# copy a tree without macOS metadata, editor droppings or test files; mtimes are not preserved (content only)
copy_tree() { # src dst [extra tar --exclude patterns…]
  local src=$1 dst=$2; shift 2
  (cd "$src" && tar -cf - --exclude='.DS_Store' --exclude='._*' --exclude='*.swp' --exclude='*~' "$@" .) | (cd "$dst" && tar -xf - -m)
}

# app: allowlist (the refine run keeps adding review artefacts next to the source)
cp "$P/original-refined/index.html" "$DIST/app/index.html"
for d in css js assets; do
  mkdir -p "$DIST/app/$d"
  copy_tree "$P/original-refined/$d" "$DIST/app/$d"
done
skipped=$(cd "$P/original-refined" && ls -1A | grep -vxE 'index\.html|css|js|assets' | tr '\n' ' ' || true)

# shared: everything but tests, the smoke page and docs
copy_tree "$P/shared" "$DIST/shared" --exclude='*.test.mjs' --exclude='*.test.js' --exclude='smoke.html' --exclude='README.md' --exclude='*.md'
mv "$DIST/shared/index.js" "$DIST/shared/index.proto.js"
cat > "$DIST/shared/index.js" <<'JS'
// GENERATED by deploy/v2/build.sh — do not edit in dist.
// The prototype barrel (index.proto.js) with the live wiring: loadSnapshot() reads /api/team-ops/* through
// deploy/v2/live/adapter.js, createLive() returns the live poller (same controller as shared/live.js).
// Page code imports this file exactly as it imports prototype/shared/index.js.
export * from './index.proto.js';
import { loadSnapshot as protoLoadSnapshot } from './index.proto.js';
import { liveLoadSnapshot, liveCreateLive } from '../live/boot.js';
export const loadSnapshot = (opts) => liveLoadSnapshot(protoLoadSnapshot, opts);
export const createLive = (store, opts) => liveCreateLive(store, opts);
JS

# tokens + fonts, plan catalog, live layer
cp "$P/original/tokens.css" "$DIST/original/tokens.css"
mkdir -p "$DIST/original/fonts"
copy_tree "$P/original/fonts" "$DIST/original/fonts"
"$NODE" "$HERE/tools/dist.mjs" catalog "$DIST" "$P/data/plan-catalog.json"   # no open questions / verification notes
cp "$HERE/live/adapter.js" "$HERE/live/synth.js" "$HERE/live/boot.js" "$DIST/live/"

# no shared module may import the barrel itself (the wrapper would then load twice under two names)
if grep -lE "from ['\"]\./index(\.proto)?\.js['\"]" "$DIST"/shared/*.js | grep -v '/shared/index.js$' | grep -q .; then
  echo "a shared module imports index.js: the live wrapper would not be the only barrel" >&2; exit 1
fi

# normalise permissions (tar -m already set mtimes to now; deploy re-chmods anyway)
find "$DIST" -type d -exec chmod 755 {} + ; find "$DIST" -type f -exec chmod 644 {} +

echo "build: $DIST"
[ -n "$skipped" ] && echo "  app: not copied from original-refined: $skipped"
BUILD_ID=$("$NODE" "$HERE/tools/dist.mjs" index "$DIST" | tee /dev/stderr | tail -1)
"$NODE" "$HERE/tools/dist.mjs" check "$DIST"
echo "build id: $BUILD_ID"
