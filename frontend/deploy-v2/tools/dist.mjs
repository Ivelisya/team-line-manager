// dist.mjs — helpers for deploy/v2/build.sh (no dependencies; node ≥ 20).
//
//   node tools/dist.mjs index <dist>     rewrite app/index.html for production (CSP-safe, live flag, no preload) → dist/index.html (site root)
//   node tools/dist.mjs check <dist>     every URL resolves, one URL per module, no data files, no real IPs /
//                                        UUIDs from the fixtures, no CSP hazards; prints the size summary
//   node tools/dist.mjs id <dist>        content hash of the tree (the build id)
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const V2 = path.dirname(HERE);
const [, , cmd, distArg] = process.argv;
const DIST = path.resolve(distArg ?? path.join(V2, 'dist'));
const TEXT = /\.(html|js|mjs|css|json|svg|txt|md)$/i;

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}
const rel = (p) => path.relative(DIST, p).split(path.sep).join('/');

export function buildId(root = DIST) {
  const h = crypto.createHash('sha256');
  for (const f of walk(root)) {
    const r = path.relative(root, f).split(path.sep).join('/');
    if (r === 'index.html') continue; // carries the id itself
    h.update(r + '\0'); h.update(fs.readFileSync(f)); h.update('\0');
  }
  h.update(fs.readFileSync(path.join(root, 'index.html'), 'utf8').replace(/<meta name="teamops-build"[^>]*>\n?\s*/g, ''));
  return h.digest('hex').slice(0, 12);
}

// ─── index: CSP-safe index.html ─────────────────────────────────────────────────────────────────────

function rewriteIndex() {
  const file = path.join(DIST, 'app/index.html');
  let html = fs.readFileSync(file, 'utf8');
  const notes = [];
  // 1. inline <script> (no src) → external classic scripts in js/ (CSP script-src 'self')
  let n = 0;
  html = html.replace(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g, (m, attrs, body) => {
    if (/type="module"/.test(attrs)) throw new Error('inline module script in index.html: move it to a file');
    const name = /refined:theme/.test(body) ? 'theme-init.js' : `inline-${++n}.js`;
    const src = `// GENERATED by deploy/v2/build.sh from an inline <script> in prototype/original-refined/index.html\n// (production CSP is script-src 'self': no inline scripts).\n${body.replace(/^\n+|\s+$/g, '')}\n`;
    fs.writeFileSync(path.join(DIST, 'app/js', name), src);
    notes.push(`inline script → js/${name}`);
    return `<script src="js/${name}"></script>`;
  });
  // 2. drop the snapshot preload (live data comes from /api/team-ops/*)
  const before = html.length;
  html = html.replace(/[ \t]*<link[^>]*href="[^"]*snapshot\.json"[^>]*>\n?/g, '');
  if (html.length !== before) notes.push('removed snapshot.json preload');
  // 3. live flag before the module script (external file, CSP-safe)
  // TEAMOPS_WRITES: the single switch for wired write actions (LIVE-MODE.md §13). Default off = read-only preview.
  const writes = process.env.WRITES === '1';
  fs.writeFileSync(path.join(DIST, 'app/js/live-flag.js'), `// GENERATED by deploy/v2/build.sh (see deploy/v2/LIVE-MODE.md).\n// TEAMOPS_LIVE: live data from /api/team-ops/*.  TEAMOPS_WRITES: team-ops DB write actions enabled (build with WRITES=1).\nglobalThis.TEAMOPS_LIVE = true;\nglobalThis.TEAMOPS_WRITES = ${writes};\n`);
  notes.push(`writes ${writes ? 'ENABLED (WRITES=1)' : 'off (read-only)'}`);
  if (!/<script type="module" src="js\/app\.js"><\/script>/.test(html)) throw new Error('index.html: module script js/app.js not found');
  html = html.replace(/([ \t]*)<script type="module" src="js\/app\.js"><\/script>/, '$1<script src="js/live-flag.js"></script>\n$1<script type="module" src="js/app.js"></script>');
  notes.push('added js/live-flag.js before the module script');
  // 4. inline event handler attributes are not allowed either
  if (/\son[a-z]+=/i.test(html)) throw new Error('index.html has an inline event handler attribute');
  // 4b. modulepreload every module the app imports statically (the import graph is 6+ levels deep: without this each
  //     level waits for the previous one — the main part of opening time on a slow link)
  const mods = [];
  const seenMod = new Set();
  const walkMods = (f) => {
    if (seenMod.has(f) || !fs.existsSync(f)) return;
    seenMod.add(f);
    const t = fs.readFileSync(f, 'utf8').replace(/^\s*\/\*[\s\S]*?\*\//gm, '').replace(/^\s*\/\/.*$/gm, '');
    for (const m of t.matchAll(/(?:^|[\s;])(?:import|export)\s[^'"]*?from\s*['"](\.{1,2}\/[^'"]+)['"]|(?:^|[\s;])import\s*['"](\.{1,2}\/[^'"]+)['"]/gm)) {
      const spec = m[1] ?? m[2];
      walkMods(path.resolve(path.dirname(f), spec));
    }
    mods.push(f);
  };
  walkMods(path.join(DIST, 'app/js/app.js'));
  const pre = mods.filter((f) => !f.endsWith(path.join('app', 'js', 'app.js')) && !f.endsWith('index.proto.js'))
    .map((f) => `  <link rel="modulepreload" href="${path.relative(DIST, f).split(path.sep).join('/')}">`).join('\n');
  html = html.replace(/(\s*<link rel="modulepreload" href="js\/app\.js">)/, `$1\n${pre}`);
  notes.push(`modulepreload: ${mods.length} modules`);
  // 5. the app lives at the site root (https://<host>/#/home): index.html moves to dist/, its own URLs get the app/
  //    prefix; everything below app/ keeps its relative URLs (../../shared → /shared, ../../data → /data exactly)
  html = html.replace(/(\s(?:src|href)=")(?!app\/|shared\/|live\/|original\/|data\/|https?:|data:|\/|#)([^"]+)"/g, '$1app/$2"');
  const root = path.join(DIST, 'index.html');
  fs.writeFileSync(root, html);
  fs.rmSync(file);
  notes.push('moved to dist/index.html (site root), URLs → app/…');
  // 6. build id (content hash, reproducible) as a meta tag
  const id = buildId();
  html = html.replace(/(<meta name="viewport"[^>]*>\n)/, `$1  <meta name="teamops-build" content="${id}">\n`);
  fs.writeFileSync(root, html);
  for (const x of notes) console.log('  index.html: ' + x);
  console.log(id);
}

// ─── check ──────────────────────────────────────────────────────────────────────────────────────────

function specifiers(file, text) {
  const out = [];
  const add = (spec, kind) => { if (spec && !/^(data:|blob:|https?:|\/\/|#|mailto:|about:)/.test(spec) && !spec.includes('${')) out.push({ spec, kind }); };
  if (/\.(m?js)$/.test(file)) {
    for (const m of text.matchAll(/\b(?:import|export)\s[^'"`;]*?\sfrom\s*['"]([^'"]+)['"]/g)) add(m[1], 'import');
    for (const m of text.matchAll(/\bimport\s*['"]([^'"]+)['"]/g)) add(m[1], 'import');
    for (const m of text.matchAll(/\bimport\(\s*['"]([^'"]+)['"]\s*\)/g)) add(m[1], 'dynamic import');
    for (const m of text.matchAll(/new URL\(\s*['"]([^'"]+)['"]\s*,\s*import\.meta\.url\s*\)/g)) add(m[1], 'new URL');
  } else if (/\.css$/.test(file)) {
    for (const m of text.matchAll(/url\(\s*['"]?([^'")]+)['"]?\s*\)/g)) add(m[1], 'css url');
  } else if (/\.html$/.test(file)) {
    for (const m of text.matchAll(/\s(?:src|href)="([^"]+)"/g)) add(m[1], 'html');
  }
  return out;
}

function fixtureSecrets() {
  const dir = path.join(V2, 'live', 'fixtures');
  if (!fs.existsSync(dir)) return null;
  const ips = new Set(), uuids = new Set();
  const doc = /^(192\.0\.2\.|198\.51\.100\.|203\.0\.113\.|127\.|0\.|255\.)/;
  for (const f of walk(dir)) {
    if (!/\.json$/.test(f)) continue;
    const t = fs.readFileSync(f, 'utf8');
    for (const m of t.matchAll(/(?<![\d.])(\d{1,3}(?:\.\d{1,3}){3})(?![\d.])/g)) if (!doc.test(m[1]) && m[1].split('.').every((x) => +x <= 255)) ips.add(m[1]);
    for (const m of t.matchAll(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/gi)) uuids.add(m[0].toLowerCase());
  }
  return { ips, uuids };
}

function check() {
  const files = walk(DIST);
  const errors = [], warnings = [];
  // 1. data files that must never ship (same rule as deploy/prod/deploy.sh)
  for (const f of files) {
    const r = rel(f);
    if (/(^|\/)(snapshot|detail|extra)\.json$/.test(r) || /(^|\/)fixtures\//.test(r) || /(^|\/)series\//.test(r)) errors.push(`data file in dist: ${r}`);
    if (/(^|\/)\.DS_Store$|\.test\.mjs$|(^|\/)smoke\.html$/.test(r)) errors.push(`dev file in dist: ${r}`);
  }
  // 1b. internal catalog to-dos never ship: open questions / verification notes (owner: they appeared in the plan popover)
  const INTERNAL = /待核实|待补/; // 待确认 is a product word (a batch waiting for its plan confirmation)
  for (const f of files.filter((x) => /\.(m?js|css|html|json)$/.test(x))) {
    const t = fs.readFileSync(f, 'utf8');
    const m = t.match(INTERNAL);
    if (m) errors.push(`${rel(f)}: internal verification wording “${m[0]}” in dist`);
    if (/\.json$/.test(f)) {
      try {
        const j = JSON.parse(t);
        if (j && typeof j === 'object' && ('questions' in j || (Array.isArray(j.plans) && j.plans.some((p) => p.pending?.length)))) errors.push(`${rel(f)}: catalog open questions / pending in dist`);
      } catch { /* not a JSON document */ }
    }
    if (/Q\d{1,2}\s*[：:（(]|（Q\d{1,2}）|catalog Q\d/.test(t)) errors.push(`${rel(f)}: catalog question reference (Qn) in dist`);
  }
  // 2. every relative URL resolves; no query strings (one URL per module → one module instance)
  let resolved = 0;
  const moduleUrls = new Map();
  for (const f of files.filter((x) => /\.(m?js|css|html)$/.test(x))) {
    let text = fs.readFileSync(f, 'utf8');
    // whole-line // comments and /* … */ blocks that start a line (doc comments quote import lines)
    if (/\.m?js$/.test(f)) text = text.replace(/^\s*\/\*[\s\S]*?\*\//gm, '').replace(/^\s*\/\/.*$/gm, '');
    for (const { spec, kind } of specifiers(f, text)) {
      if (spec.startsWith('/')) { if (!spec.startsWith('/api/') && spec !== '/admin') warnings.push(`${rel(f)}: absolute ${kind} ${spec}`); continue; }
      if (spec.includes('?')) errors.push(`${rel(f)}: ${kind} with a query string (${spec}) would create a second module instance`);
      const target = path.resolve(path.dirname(f), spec.split('?')[0]);
      if (!target.startsWith(DIST + path.sep)) { errors.push(`${rel(f)}: ${kind} ${spec} leaves dist`); continue; }
      if (!fs.existsSync(target)) { errors.push(`${rel(f)}: ${kind} ${spec} → ${rel(target)} missing`); continue; }
      resolved++;
      if (kind.includes('import')) moduleUrls.set(rel(target), (moduleUrls.get(rel(target)) ?? 0) + 1);
      // only the generated wrapper may import the prototype barrel (anything else would bypass the live wiring)
      if (rel(target) === 'shared/index.proto.js' && rel(f) !== 'shared/index.js') errors.push(`${rel(f)} imports shared/index.proto.js directly`);
    }
  }
  // 3. CSP hazards (production: script-src 'self'; no inline scripts, handlers, eval, external origins)
  for (const f of files.filter((x) => /\.(m?js|html|css)$/.test(x))) {
    const t = fs.readFileSync(f, 'utf8');
    const r = rel(f);
    if (/\.html$/.test(r) && /<script(?![^>]*\bsrc=)[^>]*>/.test(t)) errors.push(`${r}: inline <script>`);
    if (/\.html$/.test(r) && /\son[a-z]+\s*=/i.test(t)) errors.push(`${r}: inline event handler attribute`);
    if (/\.m?js$/.test(r)) {
      for (const m of t.matchAll(/<[a-z][^<>`]*\son(click|load|error|input|change|submit|mouse\w+|key\w+|focus|blur)\s*=\s*["']/gi)) errors.push(`${r}: inline handler in a template: ${m[0].slice(0, 60)}`);
      if (/\beval\s*\(|\bnew\s+Function\s*\(/.test(t)) errors.push(`${r}: eval / new Function`);
      if (/javascript:/i.test(t)) warnings.push(`${r}: contains "javascript:"`);
    }
    for (const m of t.matchAll(/\b(?:src|href)\s*=\s*["'](https?:\/\/[^"']+)/g)) errors.push(`${r}: external origin ${m[1]}`);
    for (const m of t.matchAll(/@import\s+url\(\s*["']?(https?:[^"')]+)/g)) errors.push(`${r}: external stylesheet ${m[1]}`);
  }
  // 4. no real IPs / UUIDs (anything that also appears in the captured production responses)
  const sec = fixtureSecrets();
  const seenIps = new Set();
  for (const f of files.filter((x) => TEXT.test(x))) {
    const t = fs.readFileSync(f, 'utf8');
    for (const m of t.matchAll(/(?<![\d.])(\d{1,3}(?:\.\d{1,3}){3})(?![\d.])/g)) {
      seenIps.add(m[1]);
      if (sec?.ips.has(m[1])) errors.push(`${rel(f)}: real IP from production data`);
    }
    if (sec) for (const m of t.matchAll(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/gi)) if (sec.uuids.has(m[0].toLowerCase())) errors.push(`${rel(f)}: real UUID from production data`);
  }
  if (!sec) warnings.push('live/fixtures missing: real-IP scan limited to the documentation-range check');
  // documentation (RFC 5737) and benchmark (RFC 2544, 198.18/15: shared/data.js stress rows) ranges are fine
  const odd = [...seenIps].filter((ip) => !/^(192\.0\.2\.|198\.51\.100\.|203\.0\.113\.|198\.1[89]\.|127\.0\.0\.1$|0\.0\.0\.0$)/.test(ip));
  // 5. size summary
  const groups = new Map();
  let rawAll = 0, gzAll = 0;
  for (const f of files) {
    const r = rel(f);
    const top = r.split('/').slice(0, r.startsWith('app/') || r.startsWith('original/') ? 2 : 1).join('/');
    const b = fs.readFileSync(f);
    const gz = /\.(woff2|png|jpg|gif)$/.test(f) ? b.length : zlib.gzipSync(b, { level: 9 }).length;
    const g = groups.get(top) ?? { files: 0, raw: 0, gz: 0 };
    g.files++; g.raw += b.length; g.gz += gz; groups.set(top, g);
    rawAll += b.length; gzAll += gz;
  }
  const kb = (n) => (n / 1024).toFixed(1).padStart(7) + ' KB';
  console.log('  dist layout                 files        raw       gzip');
  for (const [k, g] of [...groups].sort()) console.log(`  ${k.padEnd(26)} ${String(g.files).padStart(5)} ${kb(g.raw)} ${kb(g.gz)}`);
  console.log(`  ${'total'.padEnd(26)} ${String(files.length).padStart(5)} ${kb(rawAll)} ${kb(gzAll)}`);
  console.log(`  URLs resolved: ${resolved} · modules: ${moduleUrls.size} (each reached by one URL) · IP literals other than doc ranges: ${odd.length ? odd.join(', ') : 'none'}`);
  for (const w of warnings) console.log('  warn: ' + w);
  if (errors.length) { for (const e of errors) console.error('  ERROR: ' + e); process.exit(1); }
  console.log('  check: ok');
}

/**
 * catalog <src> — the plan catalog as it ships: no open questions, no pending ids, no verification notes in spec text
 * (same rule as prototype/original-refined/js/plans.js stripInternal).  Writes <dist>/data/plan-catalog.json.
 */
function strip(s) {
  if (/^\s*(?:待核|待补|待确认)/.test(s)) return '';
  return s.replace(/[（(][^）)]*(?:待核|待补|待确认|截图|Q\d)[^）)]*[）)]/g, '')
    .replace(/(^|[；;，,])\s*[^；;，,]*(?:待核|待补|待确认)[^；;，,]*/g, '$1')
    .replace(/^[；;，,\s]+|[；;，,\s]+$/g, '').replace(/([；;，,])\s*(?=[；;，,])/g, '').replace(/(\S)\/ /g, '$1 / ');
}
function deep(v, key = '') {
  if (typeof v === 'string') return strip(v);
  if (Array.isArray(v)) return v.map((x) => deep(x));
  if (v && typeof v === 'object') {
    const o = {};
    for (const [k, x] of Object.entries(v)) {
      if (['questions', 'pending', 'open_questions', 'verification', 'notes_internal'].includes(k)) continue;
      o[k] = deep(x, k);
    }
    return o;
  }
  void key;
  return v;
}
function catalog(src) {
  const j = JSON.parse(fs.readFileSync(src, 'utf8'));
  const out = deep(j);
  fs.mkdirSync(path.join(DIST, 'data'), { recursive: true });
  fs.writeFileSync(path.join(DIST, 'data', 'plan-catalog.json'), JSON.stringify(out, null, 1) + '\n');
  console.log(`  plan-catalog.json: ${out.plans?.length ?? 0} plans, open questions / pending / verification notes removed`);
}

if (cmd === 'index') rewriteIndex();
else if (cmd === 'catalog') catalog(process.argv[4]);
else if (cmd === 'check') check();
else if (cmd === 'id') console.log(buildId());
else { console.error('usage: dist.mjs index|check|id|catalog <dist> [src]'); process.exit(2); }
